// ---------------------------- 题面 ----------------------------
//
// 【题目描述】
// 输入两个正整数 $x_0, y_0$，求出满足下列条件的 $P, Q$ 的个数：
// 
// 1. $P,Q$ 是正整数。
// 
// 2. 要求 $P, Q$ 以 $x_0$ 为最大公约数，以 $y_0$ 为最小公倍数。
// 
// 试求：满足条件的所有可能的 $P, Q$ 的个数。
//
// 【输入格式】
// 一行两个正整数 $x_0, y_0$。
//
// 【输出格式】
// 一行一个数，表示求出满足条件的 $P, Q$ 的个数。
//
// 【样例 #1】
// 输入:
// 3 60
// 
// 输出:
// 4
// 
//
// 【提示】
// $P,Q$ 有 $4$ 种：
// 
// 1. $3, 60$。
// 2. $15, 12$。
// 3. $12, 15$。
// 4. $60, 3$。
// 
// 对于 $100\%$ 的数据，$2 \le x_0, y_0 \le {10}^5$。
// 
// **【题目来源】**
// 
// NOIP 2001 普及组第二题
//
// ---------------------------- 代码 ----------------------------

#include<iostream>
#include<iomanip>
#include<algorithm>
#include<vector>
#include <cmath>
#include<cstring>

using namespace std;

int gcd(int a, int b) {
	return b == 0 ? a : gcd(b, a % b);
}

int main() {
	ios::sync_with_stdio(false);
	cin.tie(0);

	int x, y;
	cin >> x >> y;
	long long ans = 0;
	if (x == y)ans--;
	long long n = x * y;
	for (int i =1; i <= sqrt(n); i++)
	{
		int j = x * y / i;
		if (n%i==0&&gcd(i, j) == x)ans+=2;
	}
	cout << ans;
	return 0;
}
