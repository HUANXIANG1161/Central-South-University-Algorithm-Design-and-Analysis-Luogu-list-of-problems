// ---------------------------- 题面 ----------------------------
//
// 【题目背景】
// XS 中学化学竞赛组教练是一个酷爱炉石的人。
// 
// 他会一边搓炉石一边点名以至于有一天他连续点到了某个同学两次，然后正好被路过的校长发现了然后就是一顿欧拉欧拉欧拉（详情请见已结束比赛 CON900）。
//
// 【题目描述】
// 这之后校长任命你为特派探员，每天记录他的点名。校长会提供化学竞赛学生的人数和名单，而你需要告诉校长他有没有点错名。（为什么不直接不让他玩炉石。）
//
// 【输入格式】
// 第一行一个整数 $n$，表示班上人数。
// 
// 接下来 $n$ 行，每行一个字符串表示其名字（互不相同，且只含小写字母，长度不超过 $50$）。
// 
// 第 $n+2$ 行一个整数 $m$，表示教练报的名字个数。
// 
// 接下来 $m$ 行，每行一个字符串表示教练报的名字（只含小写字母，且长度不超过 $50$）。
//
// 【输出格式】
// 对于每个教练报的名字，输出一行。
// 
// 如果该名字正确且是第一次出现，输出 `OK`，如果该名字错误，输出 `WRONG`，如果该名字正确但不是第一次出现，输出 `REPEAT`。
//
// 【样例 #1】
// 输入:
// 5
// a
// b
// c
// ad
// acd
// 3
// a
// a
// e
// 
// 输出:
// OK
// REPEAT
// WRONG
// 
//
// 【提示】
// - 对于 $40\%$ 的数据，$n\le 1000$，$m\le 2000$。
// - 对于 $70\%$ 的数据，$n\le 10^4$，$m\le 2\times 10^4$。
// - 对于 $100\%$ 的数据，$n\le 10^4$，$m≤10^5$。
// 
// ---
// 
// $\text{upd 2022.7.30}$：新增加一组 Hack 数据。
//
// ---------------------------- 代码 ----------------------------

#include <iostream>
#include <unordered_set>
#include <string>
using namespace std;

int main() {
    ios::sync_with_stdio(false);
    cin.tie(0);

    int n, m;
    string temp;
    unordered_set<string> dict, used;

    cin >> n;
    for (int i = 0; i < n; i++)
    {
        cin >> temp;
        dict.insert(temp);
    }

    cin >> m;
    for (int i = 0; i < m; i++)
    {
        cin >> temp;
        if (dict.count(temp))
        {
            if (used.count(temp))
            {
                cout << "REPEAT\n";
            }
            else
            {
                cout << "OK\n";
                used.insert(temp);
            }
        }
        else
        {
            cout << "WRONG\n";
        }
    }

    return 0;
}
