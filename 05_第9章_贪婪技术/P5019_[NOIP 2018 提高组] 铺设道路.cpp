// ---------------------------- 题面 ----------------------------
//
// 【题目背景】
// NOIP2018 提高组 D1T1
//
// 【题目描述】
// 春春是一名道路工程师，负责铺设一条长度为 $n$ 的道路。
// 
// 铺设道路的主要工作是填平下陷的地表。整段道路可以看作是 $n$ 块连续的区域，一开始，第 $i$ 块区域下陷的深度为 $d_i$ 。
// 
// 春春每天可以选择一段连续区间 $[L,R]$ ，填充这段区间中的每块区域，让其下陷深度减少 $1$。在选择区间时，需要保证，区间内的每块区域在填充前下陷深度均不为 $0$ 。
// 
// 春春希望你能帮他设计一种方案，可以在最短的时间内将整段道路的下陷深度都变为 $0$ 。
//
// 【输入格式】
// 输入文件包含两行，第一行包含一个整数 $n$，表示道路的长度。 第二行包含 $n$ 个整数，相邻两数间用一个空格隔开，第 $i$ 个整数为 $d_i$ 。
//
// 【输出格式】
// 输出文件仅包含一个整数，即最少需要多少天才能完成任务。
//
// 【样例 #1】
// 输入:
// 6
// 4 3 2 5 3 5
// 
// 输出:
// 9
//
// 【提示】
// 【样例解释】
// 
// 一种可行的最佳方案是，依次选择：
// $[1,6]$、$[1,6]$、$[1,2]$、$[1,1]$、$[4,6]$、$[4,4]$、$[4,4]$、$[6,6]$、$[6,6]$。
// 
// 【数据规模与约定】
// 
// 对于 $30\%$ 的数据，$1 ≤ n ≤ 10$ ；
// 对于 $70\%$ 的数据，$1 ≤ n ≤ 1000$ ；
// 对于 $100\%$ 的数据，$1 ≤ n ≤ 100000 , 0 ≤ d_i ≤ 10000$ 。
//
// ---------------------------- 代码 ----------------------------

#include<iostream>
#include<iomanip>
#include<algorithm>
#include<vector>
#include <cmath>
#include<cstring>
#include<queue>
#define ll long long
#define INT_MAX 2147483640
#define INF 0x3f3f3f3f3f3f3f

using namespace std;

int n;

int road[100010];

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(0);

    int n;
    cin >> n;
    for (int i = 1; i <= n; i++)
    {
        cin >> road[i];
    }
    road[n + 1] = 0; 

    int ans = 0;
    int last = 0;
    for (int i = 1; i <= n;i++)
    {
        ans += max(0, road[i]-last);
        last = road[i];
    }

    cout << ans << endl;
    return 0;
}
