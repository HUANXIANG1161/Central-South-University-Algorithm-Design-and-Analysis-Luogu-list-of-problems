// ---------------------------- 题面 ----------------------------
//
// 【题目描述】
// 所谓后缀表达式是指这样的一个表达式：式中不再引用括号，运算符号放在两个运算对象之后，所有计算按运算符号出现的顺序，严格地由左而右进行（不用考虑运算符的优先级）。
// 
// 本题中运算符仅包含 $\texttt{+-*/}$。保证对于 $\texttt{/}$ 运算除数不为 0。特别地，其中 $\texttt{/}$ 运算的结果需要**向 0 取整**（即与 C++ `/` 运算的规则一致）。
// 
// 如：$\texttt{3*(5-2)+7}$ 对应的后缀表达式为：$\texttt{3.5.2.-*7.+@}$。在该式中，`@` 为表达式的结束符号。`.` 为操作数的结束符号。
// 
//
// 【输入格式】
// 输入一行一个字符串 $s$，表示后缀表达式。
// 
//
// 【输出格式】
// 输出一个整数，表示表达式的值。
//
// 【样例 #1】
// 输入:
// 3.5.2.-*7.+@
// 输出:
// 16
//
// 【样例 #2】
// 输入:
// 10.28.30./*7.-@
// 输出:
// -7
//
// 【提示】
// 数据保证，$1 \leq |s| \leq 50$，答案和计算过程中的每一个值的绝对值不超过 $10^9$。
//
// ---------------------------- 代码 ----------------------------

#include <iostream>
#include <iomanip>
#include <stack>

using namespace std;

int main(){
	stack <int> a;
	char op='0';
	int now=0;
	int num1 = 0, num2 = 0;
	while ((op = getchar())!= '@')
	{
		if (op >= '0' && op <= '9')
		{
			now = now * 10;
			now += op - '0';
		}
		if (op == '.')
		{
			a.push(now);
			now = 0;
		}
		if (op == '+')
		{
			num1 = a.top();
			a.pop();
			num2 = a.top();
			a.pop();
			a.push(num2 + num1);
		}
		if (op == '-')
		{
			num1 = a.top();
			a.pop();
			num2 = a.top();
			a.pop();
			a.push(num2 - num1);
		}
		if (op == '*')
		{
			num1 = a.top();
			a.pop();
			num2 = a.top();
			a.pop();
			a.push(num2 * num1);
		}
		if (op == '/')
		{
			num1 = a.top();
			a.pop();
			num2 = a.top();
			a.pop();
			a.push(num2 / num1);
		}
	}
	cout << a.top();
	return 0;
}
