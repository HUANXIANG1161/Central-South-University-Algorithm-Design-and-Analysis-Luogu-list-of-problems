// ---------------------------- 题面 ----------------------------
//
// 【题目背景】
// 《爱与愁的故事第四弹·plant》第一章。
//
// 【题目描述】
// 爱与愁大神后院里种了 $n$ 棵樱花树，每棵都有美学值 $C_i(0 < C_i \le 200)$。爱与愁大神在每天上学前都会来赏花。爱与愁大神可是生物学霸，他懂得如何欣赏樱花：一种樱花树看一遍过，一种樱花树最多看 $P_i(0 \le P_i \le 100)$ 遍，一种樱花树可以看无数遍。但是看每棵樱花树都有一定的时间 $T_i(0 < T_i \le 150)$。爱与愁大神离去上学的时间只剩下一小会儿了。求解看哪几棵樱花树能使美学值最高且爱与愁大神能准时（或提早）去上学。
//
// 【输入格式】
// 共 $n+1$行：
// 
// 第 $1$ 行：现在时间 $T_s$（几时：几分），去上学的时间 $T_e$（几时：几分），爱与愁大神院子里有几棵樱花树 $n$。这里的 $T_s$，$T_e$ 格式为：`hh:mm`，其中 $0 \leq hh \leq 23$，$0 \leq mm \leq 59$，且 $hh,mm,n$ 均为非负整数。
// 
// 第 $2$ 行到第 $n+1$ 行，每行三个非负整数：看完第 $i$ 棵树的耗费时间 $T_i$，第 $i$ 棵树的美学值 $C_i$，看第 $i$ 棵树的次数 $P_i$（$P_i=0$ 表示无数次，$P_i$ 是其他数字表示最多可看的次数 $P_i$）。
//
// 【输出格式】
// 只有一个整数，表示最大美学值。
//
// 【样例 #1】
// 输入:
// 6:50 7:00 3
// 2 1 0
// 3 3 1
// 4 5 4
// 输出:
// 11
//
// 【提示】
// $100\%$ 数据：$T_e-T_s \leq 1000$（即开始时间距离结束时间不超过 $1000$ 分钟），$n \leq 10000$。保证 $T_e,T_s$ 为同一天内的时间。
// 
// 样例解释：赏第一棵樱花树一次，赏第三棵樱花树 $2$ 次。
//
// ---------------------------- 代码 ----------------------------

#include <iostream>
#include <vector>
#include <queue>
#include <cstring>
#define INF 0x3f3f3f3f
#define ll long long
using namespace std;

int n;
char maohao = ':';
int h1, m1, h2, m2;
int t[10010];
int c[10010];
int p[10010];
int dp[10010];

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(0);

    cin >> h1 >> maohao >> m1 >> h2 >> maohao >> m2>>n;
    int max_t = (h2 - h1) * 60 + m2 - m1;

    for (int i = 0; i < n; i++)
    {
        cin >> t[i] >> c[i] >> p[i];
    }

    for (int i = 0; i < n; i++)
    {
        if (p[i] == 0)
        {
            for (int j = t[i]; j <= max_t; j++)
            {
                dp[j] = max(dp[j], dp[j - t[i]] + c[i]);
            }
        }
        else
        {
            for (int k = 0; k < p[i]; k++)
            {
                for (int j = max_t; j >= t[i]; j--)
                {
                    dp[j] = max(dp[j], dp[j - t[i]] + c[i]);
                }
            }
        }
    }

    cout << dp[max_t];
    return 0;
}
