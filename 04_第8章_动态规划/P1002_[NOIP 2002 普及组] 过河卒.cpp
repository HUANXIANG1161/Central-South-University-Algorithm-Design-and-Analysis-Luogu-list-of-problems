// ---------------------------- 题面 ----------------------------
//
// 【题目描述】
// 棋盘上 $A$ 点有一个过河卒，需要走到目标 $B$ 点。卒行走的规则：可以向下、或者向右。同时在棋盘上 $C$ 点有一个对方的马，该马所在的点和所有跳跃一步可达的点称为对方马的控制点。因此称之为“马拦过河卒”。
// 
// 棋盘用坐标表示，$A$ 点 $(0, 0)$、$B$ 点 $(n, m)$，同样马的位置坐标是需要给出的。
// 
// ![](https://cdn.luogu.com.cn/upload/image_hosting/ipmwl52i.png)
// 
// 现在要求你计算出卒从 $A$ 点（不经过马的控制点）能够到达 $B$ 点的路径的条数，假设马的位置是固定不动的，并不是卒走一步马走一步。
//
// 【输入格式】
// 一行四个正整数，分别表示 $B$ 点坐标和马的坐标。
//
// 【输出格式】
// 一个整数，表示所有的路径条数。
//
// 【样例 #1】
// 输入:
// 6 6 3 3
// 
// 输出:
// 6
// 
//
// 【提示】
// 对于 $100 \%$ 的数据，$1 \le n, m \le 20$，$0 \le$ 马的坐标 $\le 20$。
// 
// 保证起点不是马的控制点。
// 
// **【题目来源】**
// 
// NOIP 2002 普及组第四题
//
// ---------------------------- 代码 ----------------------------

#include<iostream>
#include<iomanip>
#include<algorithm>
#include<vector>
#include <cmath>
#include<cstring>
#define ll long long
#define INT_MAX 2147483640

using namespace std;

 ll a[30][30];

int main() {
	ios::sync_with_stdio(false);
	cin.tie(0);

	int n, m, h1, h2;
	
	cin >> n >> m >> h1 >> h2;
	n += 2;
	m += 2;
	h1 += 2;
	h2 += 2;
	a[2][1] = 1;
	for (int i = 2; i <= n; i++)
	{
		for (int j = 2; j <= m; j++)
		{
			if ((abs(i - h1) == 2 && abs(j - h2) == 1) || (abs(i - h1)==1 && abs(j - h2) == 2)||(i==h1&&j==h2))continue;
			a[i][j] = a[i - 1][j] + a[i][j - 1];
		}
	}
	cout << a[n][m];
	return 0;
}
