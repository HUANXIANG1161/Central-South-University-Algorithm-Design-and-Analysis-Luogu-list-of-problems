// ---------------------------- 题面 ----------------------------
//
// 【题目描述】
// 长江游艇俱乐部在长江上设置了 $n$ 个游艇出租站 $1,2,\dots,n$。游客可在这些游艇出租站租用游艇，并在下游的任何一个游艇出租站归还游艇。游艇出租站 $i$ 到游艇出租站 $j$ 之间的租金为 $r_{i,j}$（$1\le i\lt j\le n$）。试设计一个算法，计算出从游艇出租站 $1$ 到游艇出租站 $n$ 所需的最少租金。
//
// 【输入格式】
// 第一行中有一个正整数 $n$，表示有 $n$ 个游艇出租站。接下来的 $n-1$ 行是一个半矩阵 $r_{i,j}$（$1\le i<j\le n$）。
//
// 【输出格式】
// 输出计算出的从游艇出租站 $1$ 到游艇出租站 $n$ 所需的最少租金。
//
// 【样例 #1】
// 输入:
// 3
// 5 15
// 7
// 输出:
// 12
//
// 【提示】
// $1\le n\le 200$，保证计算过程中任何时刻数值都不超过 $10^6$。
//
// ---------------------------- 代码 ----------------------------

#include<iostream>
#include<iomanip>
#include<algorithm>
#include<vector>
#include <cmath>
#include<cstring>
#define ll long long
#define INT_MAX 2147483640

using namespace std;

ll a[210][210];
ll dp[210];

int main() {
	ios::sync_with_stdio(false);
	cin.tie(0);

	int n;
	cin >> n;

	for (int i = 1; i < n; i++)
	{
		for (int j = i + 1; j <= n; j++)
		{
			cin >> a[i][j];
		}
		dp[i+1] = INT_MAX;
	}


	dp[1] = 0;
	for (int i = 2; i <= n; i++)
	{
		for (int j = 1; j < i; j++)
		{
			dp[i] = min(dp[i], dp[j] + a[j][i]);
		}
	}

	cout << dp[n];
	return 0;
}
