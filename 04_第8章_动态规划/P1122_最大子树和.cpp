// ---------------------------- 题面 ----------------------------
//
// 【题目描述】
// 小明对数学饱有兴趣，并且是个勤奋好学的学生，总是在课后留在教室向老师请教一些问题。一天他早晨骑车去上课，路上见到一个老伯正在修剪花花草草，顿时想到了一个有关修剪花卉的问题。于是当日课后，小明就向老师提出了这个问题：
// 
// 一株奇怪的花卉，上面共连有 $n$ 朵花，共有 $n-1$ 条枝干将花儿连在一起，并且未修剪时每朵花都不是孤立的。每朵花都有一个“美丽指数”，该数越大说明这朵花越漂亮，也有“美丽指数”为负数的，说明这朵花看着都让人恶心。所谓“修剪”，意为：去掉其中的一条枝条，这样一株花就成了两株，扔掉其中一株。经过一系列“修剪”之后，还剩下最后一株花（也可能是一朵）。老师的任务就是：通过一系列“修剪”（也可以什么“修剪”都不进行），使剩下的那株（那朵）花卉上所有花朵的“美丽指数”之和最大。
// 
// 老师想了一会儿，给出了正解。小明见问题被轻易攻破，相当不爽，于是又拿来问你。
//
// 【输入格式】
// 第一行一个整数 $n\ (1\le n\le 16000)$。表示原始的那株花卉上共 $n$ 朵花。
// 
// 第二行有 $n$ 个整数，第 $i$ 个整数表示第 $i$ 朵花的美丽指数。
// 
// 接下来 $n-1$ 行每行两个整数 $a,b$，表示存在一条连接第 $a$ 朵花和第 $b$ 朵花的枝条。
//
// 【输出格式】
// 一个数，表示一系列“修剪”之后所能得到的“美丽指数”之和的最大值。保证绝对值不超过 $2147483647$。
//
// 【样例 #1】
// 输入:
// 7
// -1 -1 -1 1 1 1 0
// 1 4
// 2 5
// 3 6
// 4 7
// 5 7
// 6 7
// 
// 输出:
// 3
//
// 【提示】
// ### 数据范围及约定
// 
// - 对于 $60\%$ 的数据，有 $1\le n\le 1000$；
// - 对于 $100\%$ 的数据，有 $1\le n\le 16000$，所有花朵的美丽指数范围在 $[-10^9,10^9]$ 内。
//
// ---------------------------- 代码 ----------------------------

#include<iostream>
#include<iomanip>
#include<algorithm>
#include<vector>
#include <cmath>
#include<cstring>
#define ll long long
#define INT_MAX 2147483640
#define INF 0x3f3f3f3f

using namespace std;

int value[16010];
int dp[16010];
vector<int> edge[16010];

void dfs(int x,int father)
{
	dp[x] = value[x];

	for (int i = 0; i < edge[x].size(); i++)
	{
		if (edge[x][i] != father)
		{
			dfs(edge[x][i], x);
			if (dp[edge[x][i]]>0)
			{
				dp[x] += dp[edge[x][i]];
			}
		}
	}
}


int main()
{
	ios::sync_with_stdio(false);
	cin.tie(0);

	int n;
	cin >> n;
	for (int i = 1; i <= n; i++)
	{
		cin >> value[i];
	}

	for (int i = 0; i < n - 1; i++)
	{
		int a, b;
		cin >> a >> b;

		edge[a].push_back(b);
		edge[b].push_back(a);
	}

	int ans = -0x3f3f3f3f;
	dfs(1, 0);
	for (int i = 1; i <= n; i++)
	{
		ans = max(ans, dp[i]);
	}

	cout << ans;
	return 0;
}
