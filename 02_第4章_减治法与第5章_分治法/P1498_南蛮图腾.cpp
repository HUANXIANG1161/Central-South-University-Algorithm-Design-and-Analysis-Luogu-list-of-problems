// ---------------------------- 题面 ----------------------------
//
// 【题目背景】
// 自从到了南蛮之地，孔明不仅把孟获收拾的服服帖帖，而且还发现了不少少数民族的智慧，他发现少数民族的图腾往往有着一种分形的效果，在得到了酋长的传授后，孔明掌握了不少绘图技术，但唯独不会画他们的图腾，于是他找上了你的爷爷的爷爷的爷爷的爷爷……帮忙，作为一个好孙子的孙子的孙子的孙子……你能做到吗？
//
// 【题目描述】
// 给定一个正整数 $n$，参考输出样例，输出图形。
//
// 【输入格式】
// 每个数据输入一个正整数 $n$，表示图腾的大小（此大小非彼大小）。
//
// 【输出格式】
// 这个大小的图腾。
//
// 【样例 #1】
// 输入:
// 2
// 输出:
//    /\
//   /__\
//  /\  /\
// /__\/__\
// 
//
// 【样例 #2】
// 输入:
// 3
// 输出:
//        /\
//       /__\
//      /\  /\
//     /__\/__\
//    /\      /\
//   /__\    /__\
//  /\  /\  /\  /\
// /__\/__\/__\/__\
//
// 【提示】
// 数据保证，$1 \leq n \leq 10$。
//
// ---------------------------- 代码 ----------------------------

#include<iostream>
#include<iomanip>
#include<algorithm>
#include<vector>
#include <cmath>
#include<cstring>

using namespace std;

int n;
char a[3034][3034];


int main() {
	ios::sync_with_stdio(false);
	cin.tie(0);

	cin >> n;
	memset(a, ' ', sizeof(a));
	a[1][1] = a[1][4] = ' ';
	a[1][2] = a[2][1] = '/';
	a[1][3] = a[2][4] = '\\';
	a[2][2] = a[2][3] = '_';

	int h = 2, w = 4;

	for (int i = 1; i < n; i++)
	{
		for (int j = 1; j <= h; j++)
		{
			for (int k = 1; k <= w; k++)
			{
				a[j + h][k] = a[j][k];
				a[j + h][k + w] = a[j][k];
				a[j][k] = ' ';
			}
		}

		for (int j = 1; j <= h; j++)
		{
			for (int k = 1; k <= w; k++)
			{
				a[j][k + w / 2] = a[j + h][k];
			}
		}
		h *= 2;
		w *= 2;
	}

	for (int i = 1; i <= h; i++)
	{
		for (int j = 1; j <= w; j++)
		{
			cout << a[i][j];
		}
		cout << endl;
	}
	return 0;
}
